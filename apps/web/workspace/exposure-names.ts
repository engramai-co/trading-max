/** Shorter Chinese names than the CLDR defaults, as used elsewhere in the app. */
const zhCountries: Record<string, string> = { HK: "香港", MO: "澳门", AE: "阿联酋" };
const notCountries: Record<string, string> = {
  unclassified: "未分类",
  "cash & derivatives": "现金与衍生品",
  "cash and/or derivatives": "现金与衍生品",
  cash: "现金",
  other: "其他",
};

const regionNames = new Map<Locale, Intl.DisplayNames>();
function regions(locale: Locale) {
  let names = regionNames.get(locale);
  if (!names) {
    names = new Intl.DisplayNames([locale === "zh" ? "zh-CN" : "en-GB"], { type: "region" });
    regionNames.set(locale, names);
  }
  return names;
}

/** ISO code for a reported country name, so "Taiwan" and "Taiwan Region" are one place. */
export function countryCode(name: string | null | undefined) {
  return name ? (countryCodes[name.trim().toLowerCase()] ?? null) : null;
}

export function countryName(name: string | null | undefined, locale: Locale) {
  if (!name) return "—";
  const code = countryCode(name);
  if (!code) return locale === "zh" ? (notCountries[name.trim().toLowerCase()] ?? name) : name;
  if (locale === "zh" && zhCountries[code]) return zhCountries[code];
  try {
    return regions(locale).of(code) ?? name;
  } catch {
    return name;
  }
}

