"""Compile the pinned Natural Earth 110m GeoJSON into Equal Earth SVG paths."""

import argparse
import hashlib
import json
import math
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parents[1]
URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/"
SOURCES = {
    "ne_110m_admin_0_countries.geojson": "6866c877d39cba9c357620878839b336d569f8c662d3cfab4cb1dbe2d39c977f",
    "ne_110m_land.geojson": "9e0729ee253ca7d7a5c4ae9395fb1902264c5377c52e224d13dd85010e2835d9",
}
MARKETS = {
    "us": {"USA"},
    "ca": {"CAN"},
    "uk": {"GBR"},
    "eu": {
        "AUT",
        "BEL",
        "DEU",
        "DNK",
        "ESP",
        "FIN",
        "FRA",
        "IRL",
        "ITA",
        "NLD",
        "NOR",
        "PRT",
        "SWE",
    },
    "ch": {"CHE"},
    "jp": {"JPN"},
    "kr": {"KOR"},
    "tw": {"TWN"},
    "in": {"IND"},
    "au": {"AUS"},
}
# Match the approved artwork: a near-global view, cropped south of the inhabited land.
# The viewBox includes a narrow margin for the labels on the Pacific side.
SCALE = 143


def project(lon: float, lat: float) -> tuple[float, float]:
    """Equal Earth, Šavrič, Patterson and Jenny (2018), central meridian 0°."""
    a1, a2, a3, a4 = 1.340264, -0.081106, 0.000893, 0.003796
    theta = math.asin(math.sqrt(3) / 2 * math.sin(math.radians(lat)))
    t2 = theta * theta
    t6 = t2**3
    derivative = a1 + 3 * a2 * t2 + t6 * (7 * a3 + 9 * a4 * t2)
    x = math.radians(lon) * math.cos(theta) / (math.sqrt(3) / 2 * derivative)
    y = theta * (a1 + a2 * t2 + t6 * (a3 + a4 * t2))
    return 400 + SCALE * x, 202 - SCALE * y


def load(name: str, source_dir: Path | None) -> list:
    if source_dir is None:
        response = httpx.get(URL + name, timeout=30)
        response.raise_for_status()
        payload = response.content
    else:
        payload = (source_dir / name).read_bytes()
    if hashlib.sha256(payload).hexdigest() != SOURCES[name]:
        raise ValueError(f"Natural Earth checksum mismatch: {name}")
    return json.loads(payload)["features"]


def paths(feature: dict) -> str:
    geometry = feature["geometry"]
    polygons = (
        [geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"]
    )
    result = []
    for polygon in polygons:
        # Antarctica is outside the geographic frame. Keep offshore islands.
        if max(lat for _, lat in polygon[0]) < -60:
            continue
        for ring in polygon:
            points = list(
                dict.fromkeys(
                    (round(x * 2) / 2, round(y * 2) / 2)
                    for x, y in (project(*point) for point in ring)
                )
            )
            if len(points) >= 3:
                result.append("M" + " ".join(f"{x:g},{y:g}" for x, y in points) + "Z")
    return "".join(result)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source-dir", type=Path, help="Read the pinned files from a local directory."
    )
    args = parser.parse_args()
    countries = load("ne_110m_admin_0_countries.geojson", args.source_dir)
    land = load("ne_110m_land.geojson", args.source_dir)
    # French Guiana is part of France in this dataset but not in the European region.
    for feature in countries:
        if feature["properties"]["ADM0_A3"] == "FRA":
            feature["geometry"]["coordinates"] = [
                polygon for polygon in feature["geometry"]["coordinates"] if polygon[0][0][1] > 0
            ]
    markets = {
        scope: "".join(paths(item) for item in countries if item["properties"]["ADM0_A3"] in codes)
        for scope, codes in MARKETS.items()
    }
    if not all(markets.values()):
        raise ValueError("Natural Earth geometry is missing a market")
    output = ROOT / "apps/web/workspace/global-market-geometry.ts"
    output.write_text(
        "// Generated by tools/generate_global_market_map.py from public-domain Natural Earth 110m.\n"
        + 'export const WORLD_VIEWBOX = "47 0 730 337";\n'
        + f"export const WORLD_LAND = {json.dumps(''.join(map(paths, land)))};\n"
        + f"export const MARKET_PATHS = {json.dumps(markets, indent=2)} as const;\n"
    )


if __name__ == "__main__":
    main()
